def names(table: Dict[int, str], codes: Iterable[int]) -> List[str]:
    """Names for *codes*, keeping unknown numbers visible as ``UNKNOWN_<n>``."""
    return [table.get(code, f"UNKNOWN_{code}") for code in codes]
